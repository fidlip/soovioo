namespace Soovioo.Api.Payments;

/// <summary>Who owes money for this payment — deliberately a much smaller
/// set of options than <see cref="Events.EventAudience"/>: no "OnlyMe"
/// (a payment always has an actual payer, never just the creator), and
/// targeting is restricted to classes/parents/students (no teachers —
/// teachers don't pay school fees). <see cref="Everyone"/> is the enum's
/// default (0) for the same reason as EventAudience.</summary>
public enum PaymentAudience
{
    Everyone = 0,

    /// <summary>Audience is the union of whatever <see cref="PaymentSchoolClass"/>,
    /// <see cref="PaymentParent"/> and <see cref="PaymentStudent"/> rows exist
    /// for this payment — resolved into actual target student ids by
    /// <see cref="PaymentRecipientGenerator"/>.</summary>
    Selected = 1,
}

/// <summary>How <see cref="Payment.Amount"/> is interpreted when generating
/// each student's <see cref="PaymentRecipient"/> row.</summary>
public enum PaymentAmountType
{
    /// <summary>Every targeted student owes exactly <see cref="Payment.Amount"/>.</summary>
    FixedPerStudent = 0,

    /// <summary><see cref="Payment.Amount"/> is the total; each targeted
    /// student owes an equal share (see <see cref="PaymentRecipientGenerator"/>
    /// for the rounding rule — remainder cents aren't redistributed).</summary>
    TotalSplitEvenly = 1,
}

/// <summary>How often a new installment (a fresh <see cref="PaymentRecipient"/>
/// batch) is generated. <see cref="None"/> payments generate exactly one
/// batch, synchronously, at creation time.</summary>
public enum PaymentRecurrence
{
    None = 0,
    Monthly = 1,
    Semiannually = 2,
}

/// <summary>A one-off or recurring charge (akce poplatek, kroužek, ...).
/// Zadává Admin/Teacher — see ROADMAP "Správa financí". Each installment's
/// actual per-student amount/recipients live in <see cref="Recipients"/>,
/// generated by <see cref="PaymentRecipientGenerator"/> — this row only
/// holds the targeting criteria and recurrence cursor, not the resolved
/// student list, so a recurring payment can re-resolve targets (e.g. a
/// student who joined the class later) on each new installment.</summary>
public class Payment
{
    public int Id { get; set; }

    public int SchoolId { get; set; }
    public Evidence.School? School { get; set; }

    public required string Title { get; set; }
    public string? Description { get; set; }

    /// <summary>Due date of the first (or only, if not recurring) installment.
    /// Immutable — later installments' due dates are derived from this one
    /// via <see cref="PaymentRecipientGenerator.Advance"/>, not stored here.</summary>
    public DateOnly DueDate { get; set; }

    public PaymentAmountType AmountType { get; set; }
    public decimal Amount { get; set; }

    public PaymentRecurrence Recurrence { get; set; }

    /// <summary>Only meaningful when <see cref="Recurrence"/> != None. Defaults
    /// (server-side, if the creator didn't supply one) to June 30 of the
    /// nearest running Czech school year — see
    /// <see cref="PaymentRecipientGenerator.DefaultSchoolYearEndDate"/>.</summary>
    public DateOnly? RecurrenceEndDate { get; set; }

    /// <summary>Mutable cursor the recurring background job
    /// (<see cref="PaymentRecurringInstallmentsJob"/>) advances: the due date
    /// of the NEXT installment still to be generated, or null once there are
    /// no more (either Recurrence is None — the single batch was already
    /// generated at creation — or the next date would fall after
    /// <see cref="RecurrenceEndDate"/>).</summary>
    public DateOnly? NextOccurrenceDueDate { get; set; }

    public int CreatedByUserId { get; set; }

    public PaymentAudience Audience { get; set; }

    public ICollection<PaymentSchoolClass> SchoolClasses { get; set; } = new List<PaymentSchoolClass>();
    public ICollection<PaymentParent> Parents { get; set; } = new List<PaymentParent>();
    public ICollection<PaymentStudent> Students { get; set; } = new List<PaymentStudent>();

    public ICollection<PaymentRecipient> Recipients { get; set; } = new List<PaymentRecipient>();
}
